import { NextRequest, NextResponse } from 'next/server';
import { getServerSession } from 'next-auth/next';
import { authOptions } from '@/lib/auth';
import { logAudit } from '@/lib/auditLog';
import { getPool } from '@/lib/db';

export async function POST(request: NextRequest) {
  const session = await getServerSession(authOptions);
  
  if (!session?.user) {
    return NextResponse.json({ error: 'Unauthorized' }, { status: 401 });
  }

  try {
    const body = await request.json();
    const { title, department, positionLevel } = body;

    if (!title || !department) {
      return NextResponse.json(
        { error: 'Title and department are required' },
        { status: 400 }
      );
    }

    // Get API key from system settings or environment
    async function getSystemSetting(key: string): Promise<string | null> {
      const client = await getPool().connect();
      try {
        const res = await client.query('SELECT value FROM "SystemSetting" WHERE key = $1', [key]);
        if (res.rows.length > 0) {
          return res.rows[0].value;
        }
        return null;
      } finally {
        client.release();
      }
    }

    const dbApiKey = await getSystemSetting('geminiApiKey');
    const apiKey = dbApiKey || process.env.GOOGLE_API_KEY;
    
    if (!apiKey) {
      console.error('AI Job Description: Gemini API Key not configured. AI features unavailable.');
      return NextResponse.json(
        { error: 'AI features are not available due to missing API Key configuration. Please configure the Gemini API Key in System Settings.' },
        { status: 503 }
      );
    }

    // Create a comprehensive prompt for job description generation
    const prompt = `You are an expert HR professional and job description writer. Generate a professional, comprehensive job description for the following position:

Position Title: ${title}
Department: ${department}
Position Level: ${positionLevel || 'Not specified'}

Please create a detailed job description that includes:

1. **Job Summary**: A compelling overview of the role and its importance to the organization
2. **Key Responsibilities**: Main duties and tasks (5-8 specific, actionable bullet points)
3. **Required Qualifications**: Essential skills, experience, and education requirements
4. **Preferred Qualifications**: Nice-to-have skills and experience that would be beneficial
5. **Key Competencies**: Important soft skills and professional attributes
6. **Working Conditions**: Any relevant work environment details, benefits, or company culture information

Requirements:
- Format the response in clean HTML with proper headings (h2, h3) and bullet points (ul, li)
- Make it professional, clear, and comprehensive
- Tailor the content specifically to the position title and department
- Include industry-relevant terminology and expectations
- Make it engaging and attractive to potential candidates
- Ensure it's realistic and achievable for the specified position level
- Use strong action verbs and specific responsibilities
- Include both technical and soft skill requirements

Return ONLY the HTML-formatted job description without any additional text, markdown formatting, or explanations.`;

    // Call Google Gemini API directly
    const url = "https://generativelanguage.googleapis.com/v1beta/models/gemini-2.0-flash:generateContent";
    
    const fetchRes = await fetch(url, {
      method: "POST",
      headers: {
        "Content-Type": "application/json",
        "X-goog-api-key": apiKey,
      },
      body: JSON.stringify({
        contents: [
          {
            role: "user",
            parts: [{ text: prompt }]
          }
        ]
      }),
    });

    if (!fetchRes.ok) {
      const errorText = await fetchRes.text();
      throw new Error(`Gemini API error: ${fetchRes.status} ${fetchRes.statusText} - ${errorText}`);
    }

    const data = await fetchRes.json();
    const generatedDescription = data.candidates?.[0]?.content?.parts?.[0]?.text || "";

    if (!generatedDescription.trim()) {
      throw new Error('No content generated by AI');
    }

    // Log the AI generation activity
    await logAudit(
      'AUDIT',
      `AI job description generated for position: ${title} in ${department}`,
      'API:AI:GenerateJobDescription',
      session.user.id,
      { title, department, positionLevel }
    );

    return NextResponse.json({
      description: generatedDescription,
      success: true
    });

  } catch (error) {
    console.error('Error generating job description:', error);
    await logAudit(
      'ERROR',
      `Failed to generate job description: ${(error as Error).message}`,
      'API:AI:GenerateJobDescription',
      session.user?.id
    );
    
    return NextResponse.json(
      { error: `Failed to generate job description: ${(error as Error).message}` },
      { status: 500 }
    );
  }
} 