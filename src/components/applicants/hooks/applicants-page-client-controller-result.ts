import type {
  ApplicantsPageClientControllerResult,
  BuildApplicantsPageClientControllerInput,
} from './applicants-page-client-controller-result-types';

export function buildApplicantsPageClientController<TInput extends BuildApplicantsPageClientControllerInput>({
  sessionGateMessage,
  isMobile,
  filterControls,
  sidebarFilterRef,
  filters,
  effectiveData,
  advancedQuery,
  handleFilterChange,
  horizontalSelectedFitScoreGrades,
  horizontalSelectedMatchingFitScoreGrades,
  aiSearchReasoning,
  aiMatchedApplicantIds,
  aiRecordCount,
  isAiSearchActive,
  isAiSearching,
  isSearchDrawerOpen,
  setIsSearchDrawerOpen,
  handleAiSearch,
  cancelAiSearch,
  applicantSettings,
  settingsLoading,
  settingsError,
  clearSettingsError,
  pageSize,
  sortColumn,
  sortDirection,
  importExport,
  uiState,
  availableStages,
  applicantsToRender,
  allPinnedApplicants,
  displayedApplicants,
  isLoading,
  tableLoading,
  tableHeight,
  page,
  setPage,
  total,
  totalPages,
  fetchTableData,
  refreshApplicantInList,
  fetchAllPinnedApplicants,
  applicantScoreCounts,
  isFilterDataLoading,
  rowActions,
  bulkActions,
  filteredApplicants,
  refreshCurrentApplicantsPage,
}: TInput): ApplicantsPageClientControllerResult<TInput> {
  return {
    sessionGateMessage,
    layout: {
      isMobile,
      isFilterPinned: filterControls.isFilterPinned,
    },
    refs: {
      sidebarFilterRef,
    },
    filters: {
      values: filters,
      activeFilterCount: effectiveData.activeFilterCount,
      advancedQuery,
      handleFilterChange,
      onFilterChange: filterControls.onFilterChange,
      onClearAll: filterControls.handleClearAllFilters,
      onTogglePinned: filterControls.handleToggleFilterPin,
      horizontalSelectedFitScoreGrades,
      horizontalSelectedMatchingFitScoreGrades,
      onAppliedGradeToggle: filterControls.handleHorizontalFitScoreGradeToggle,
      onMatchingGradeToggle: filterControls.handleHorizontalMatchingFitScoreGradeToggle,
      onClearHorizontalFitScores: filterControls.clearAllHorizontalFitScoreFilters,
    },
    ai: {
      aiSearchReasoning,
      aiMatchedApplicantIds,
      aiRecordCount,
      isAiSearchActive,
      isAiSearching,
      isSearchDrawerOpen,
      setIsSearchDrawerOpen,
      handleAiSearch,
      cancelAiSearch,
    },
    settings: {
      applicantSettings,
      settingsLoading,
      settingsError,
      clearSettingsError,
      pageSize,
      sortColumn,
      sortDirection,
      exportImportFeatureEnabled: importExport.exportImportFeatureEnabled,
      onSettingsChange: uiState.handleSettingsChange,
      onPageSizeChange: uiState.handlePageSizeChange,
      onSortChange: uiState.handleSortChange,
    },
    available: {
      positions: effectiveData.effectivePositions,
      stages: effectiveData.effectiveStages,
      recruiters: effectiveData.effectiveRecruiter,
      sources: effectiveData.effectiveSources,
      rawStages: availableStages,
    },
    permissions: {
      canEditApplicants: effectiveData.canEditApplicants,
      canDeleteApplicants: effectiveData.canDeleteApplicants,
      canChangeStatus: effectiveData.canChangeStatus,
      canBulkChangeStatus: effectiveData.canBulkChangeStatus,
      canViewDetailed: effectiveData.canViewDetailed,
      canAssignSource: effectiveData.canAssignSource,
      canAssignRecruiter: effectiveData.canAssignRecruiter,
    },
    table: {
      applicantsToRender,
      allPinnedApplicants,
      displayedApplicants,
      isLoading,
      tableLoading,
      tableHeight,
      page,
      setPage,
      total,
      totalPages,
      fetchTableData,
      refreshApplicantInList,
      fetchAllPinnedApplicants,
    },
    scoring: {
      applicantScoreCounts,
      isFilterDataLoading,
    },
    rows: rowActions,
    bulk: bulkActions,
    modals: uiState,
    importExport,
    searchExperience: {
      applicants: filteredApplicants,
      stageNames: effectiveData.stageNames,
      stageColors: effectiveData.stageColors,
    },
    refreshCurrentApplicantsPage,
  };
}
